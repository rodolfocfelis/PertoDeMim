-- Estrutura inicial para bases PostgreSQL novas.
-- Em bases antigas já populadas, o Flyway cria baseline em V1 sem executar este script.
CREATE TABLE tb_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT
);

CREATE TABLE professional (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    user_email VARCHAR(254) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    category_id BIGINT REFERENCES category(id),
    city VARCHAR(100),
    zip_code VARCHAR(10),
    street VARCHAR(150),
    address_number VARCHAR(20),
    complement VARCHAR(100),
    state VARCHAR(2),
    latitude NUMERIC(10, 8) NOT NULL,
    longitude NUMERIC(11, 8) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_professional_category ON professional(category_id);
CREATE INDEX idx_professional_user_email ON professional(user_email);
CREATE INDEX idx_professional_active ON professional(active);
