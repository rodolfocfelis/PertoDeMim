CREATE TABLE review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES tb_users(id),
    professional_id BIGINT NOT NULL REFERENCES professional(id),
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(2000),
    CONSTRAINT uk_review_user_professional UNIQUE (user_id, professional_id)
);
CREATE INDEX idx_review_professional ON review(professional_id);
